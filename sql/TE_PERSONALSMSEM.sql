    CLAVEINTERNA     VARCHAR2(20)  NOT NULL,
    CLAVE            VARCHAR2(40),
    NOMBRECOMPLETO   VARCHAR2(200) NOT NULL,
    ADSCRIPCION      VARCHAR2(200),
    IDMONGOFOTO      VARCHAR2(40),
    IDMONGOFIRMA     VARCHAR2(40),
    CADENAQR         VARCHAR2(500),
    FECALTA          DATE,
    FECCAPTURA       DATE,
    FECIMPRESION     DATE,
    USUARIOESTACION  VARCHAR2(40),
    CONSTRAINT PK_TE_PERSONALSMSEM PRIMARY KEY (CLAVEINTERNA)
);


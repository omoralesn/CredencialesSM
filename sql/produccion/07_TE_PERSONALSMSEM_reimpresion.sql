-- Reimpresiones físicas (no cuentan archivo / preview).
-- NUMREIMPRESIONES: veces que se reimprimió en impresora tras la primera física.
-- FECREIMPRESION: fecha de la última reimpresión física.
-- IMPFISICA: 'S' cuando ya hubo al menos una impresión física.

BEGIN
    EXECUTE IMMEDIATE 'ALTER TABLE TE_PERSONALSMSEM ADD NUMREIMPRESIONES NUMBER(6) DEFAULT 0 NOT NULL';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -1430 THEN RAISE; END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE 'ALTER TABLE TE_PERSONALSMSEM ADD FECREIMPRESION DATE';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -1430 THEN RAISE; END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE 'ALTER TABLE TE_PERSONALSMSEM ADD IMPFISICA VARCHAR2(1) DEFAULT ''N''';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -1430 THEN RAISE; END IF;
END;
/

UPDATE TE_PERSONALSMSEM
SET NUMREIMPRESIONES = NVL(NUMREIMPRESIONES, 0),
    IMPFISICA = NVL(IMPFISICA, 'N')
WHERE NUMREIMPRESIONES IS NULL OR IMPFISICA IS NULL;

COMMIT;

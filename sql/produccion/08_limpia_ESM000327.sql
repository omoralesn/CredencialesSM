-- Deja ESM000327 como pendiente de impresión. No toca otros folios.
-- Conserva clave, nombre, adscripción, QR y fecha de alta.

UPDATE TE_PERSONALSMSEM
SET IDMONGOFOTO = NULL,
    IDMONGOFIRMA = NULL,
    FECCAPTURA = NULL,
    FECIMPRESION = NULL,
    USUARIOESTACION = NULL,
    NUMREIMPRESIONES = 0,
    FECREIMPRESION = NULL,
    IMPFISICA = 'N'
WHERE CLAVEINTERNA = 'ESM000327';

COMMIT;

SELECT CLAVEINTERNA, CLAVE, NOMBRECOMPLETO,
       IDMONGOFOTO, IDMONGOFIRMA,
       TO_CHAR(FECALTA, 'DD/MM/YYYY') FECALTA,
       TO_CHAR(FECCAPTURA, 'DD/MM/YYYY') FECCAPTURA,
       TO_CHAR(FECIMPRESION, 'DD/MM/YYYY') FECIMPRESION,
       USUARIOESTACION, NUMREIMPRESIONES, IMPFISICA
FROM TE_PERSONALSMSEM
WHERE CLAVEINTERNA = 'ESM000327';

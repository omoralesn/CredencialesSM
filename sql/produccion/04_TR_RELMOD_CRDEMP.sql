-- Relación perfil CRDEMP ↔ módulo de estación EST_CRDEMP.
-- Los usuarios con CVE_PERFIL = CRDEMP en TE_USUARIOS heredan este acceso.

INSERT INTO TR_RELMOD (CVE_PERFIL, CVE_MODULO, CVE_MODPADRE)
SELECT 'CRDEMP', 'EST_CRDEMP', '0' FROM DUAL
WHERE NOT EXISTS (
    SELECT 1 FROM TR_RELMOD
    WHERE TRIM(CVE_PERFIL) = 'CRDEMP'
      AND TRIM(CVE_MODULO) = 'EST_CRDEMP'
      AND TRIM(CVE_MODPADRE) = '0'
);

COMMIT;

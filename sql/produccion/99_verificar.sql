-- Comprobaciones post-despliegue.

SELECT CVE_PERFIL, CMPDESCPERFIL
FROM TE_PERFILES
WHERE TRIM(CVE_PERFIL) = 'CRDEMP';

SELECT CVE_MODULO, CVE_MODPADRE, DESC_MOD, FECVIG, FECVEN, ESWEB,
       CASE WHEN TRUNC(SYSDATE) BETWEEN TRUNC(FECVIG) AND TRUNC(FECVEN)
            THEN 'VIGENTE' ELSE 'VENCIDO/FUERA' END AS ESTADO
FROM TE_MODULOS
WHERE TRIM(CVE_MODULO) = 'EST_CRDEMP';

SELECT CVE_PERFIL, CVE_MODULO, CVE_MODPADRE
FROM TR_RELMOD
WHERE TRIM(CVE_PERFIL) = 'CRDEMP'
  AND TRIM(CVE_MODULO) = 'EST_CRDEMP';

SELECT CVEUSU, NOMUSU, CVE_PERFIL, DESHAB
FROM TE_USUARIOS
WHERE TRIM(CVE_PERFIL) = 'CRDEMP'
ORDER BY CVEUSU;

-- Usuarios que podrían entrar hoy (perfil + módulo vigente + relación):
SELECT U.CVEUSU, U.NOMUSU, M.FECVIG, M.FECVEN
FROM TE_USUARIOS U
JOIN TR_RELMOD R
  ON TRIM(R.CVE_PERFIL) = TRIM(U.CVE_PERFIL)
JOIN TE_MODULOS M
  ON TRIM(M.CVE_MODULO) = TRIM(R.CVE_MODULO)
 AND TRIM(M.CVE_MODPADRE) = TRIM(R.CVE_MODPADRE)
WHERE TRIM(U.CVE_PERFIL) = 'CRDEMP'
  AND U.DESHAB IS NULL
  AND TRIM(M.CVE_MODULO) = 'EST_CRDEMP'
  AND TRUNC(SYSDATE) BETWEEN TRUNC(M.FECVIG) AND TRUNC(M.FECVEN);
